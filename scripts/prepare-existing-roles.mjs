// Derive a separate template, so existing-role deployments never manage IAM roles or policies.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
export function existingRolesTemplate(source) {
  let result = source;
  for (const name of ["WellyncBackendFunctionRole", "FrontendFunctionRole"]) {
    const pattern = new RegExp(`^  ${name}:\\n[\\s\\S]*?(?=^  [A-Za-z]|$(?![\\s\\S]))`, "m");
    if (!pattern.test(result)) throw new Error(`Missing managed role resource: ${name}`);
    result = result.replace(pattern, "");
  }
  const definitions = [
    ["BackendExecutionRoleArn", "Existing dedicated backend Lambda role ARN; runtime policy is configured outside CloudFormation."],
    ["FrontendExecutionRoleArn", "Existing separate frontend Lambda role ARN; runtime policy is configured outside CloudFormation."]
  ].map(([name, description]) => `  ${name}:\n    Type: String\n    AllowedPattern: '^arn:aws:iam::[0-9]{12}:role/[A-Za-z0-9+=,.@_/-]+$'\n    Description: ${description}\n`).join("");
  result = result.replace("Parameters:\n", () => `Parameters:\n${definitions}`);
  result = result.replace("Rules:\n", "Rules:\n  SeparateExecutionRoles:\n    Assertions:\n      - Assert: !Not [!Equals [!Ref BackendExecutionRoleArn, !Ref FrontendExecutionRoleArn]]\n        AssertDescription: Frontend and backend must use separate execution roles.\n");
  result = result.replaceAll("!GetAtt WellyncBackendFunctionRole.Arn", "!Ref BackendExecutionRoleArn").replaceAll("!GetAtt FrontendFunctionRole.Arn", "!Ref FrontendExecutionRoleArn");
  if (result.includes("Type: AWS::IAM::") || !result.includes("Role: !Ref BackendExecutionRoleArn") || !result.includes("Role: !Ref FrontendExecutionRoleArn")) throw new Error("External-role template must not manage IAM resources");
  return "# Generated by node scripts/prepare-existing-roles.mjs; edit template.yaml then regenerate.\n# Existing roles require authorized out-of-stack runtime permissions. See docs/existing-roles.md.\n" + result;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync("lambda-backend/template-existing-roles.yaml", existingRolesTemplate(readFileSync("lambda-backend/template.yaml", "utf8")));
  console.log("Generated lambda-backend/template-existing-roles.yaml; no AWS resources were changed.");
}
